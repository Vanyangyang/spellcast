import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../spellcast-bridge/src/artifact-runtime.js', import.meta.url), 'utf8');
const messages = [], listeners = {}, parent = { postMessage: message => messages.push(message) };
const port = { postMessage: message => messages.push(message), start() {}, onmessage: null };
const context = { parent, TextEncoder, location: { pathname: '/work/index.html' }, document: { body: null }, addEventListener: (name, fn) => { (listeners[name] ??= []).push(fn); } };
context.window = context;
vm.createContext(context); vm.runInContext(source, context);
const sdk = context.spellcast;
assert.equal(messages[0].type, 'spellcast:ready');
assert.throws(() => sdk.setState({ speed: 2 }), /Await/);
listeners.message[0]({ source: {}, data: { type: 'spellcast:init', state: { forged: true } }, ports: [port] });
assert.throws(() => sdk.setState({ speed: 2 }), /Await/, 'An unrelated window cannot initialize the channel.');
listeners.message[0]({ source: parent, data: { type: 'spellcast:init', state: { speed: 3, note: 'kept' } }, ports: [port] });
assert.equal((await sdk.ready).speed, 3);
sdk.setState({ speed: 4 }); sdk.select({ ids: ['rotor'], label: '风杯' });
assert.equal(sdk.state.speed, 4); assert.equal(sdk.state.note, 'kept'); assert.equal(sdk.state.selection.ids[0], 'rotor');
const snapshot = sdk.state; snapshot.speed = 99; assert.equal(sdk.state.speed, 4, 'Callers cannot mutate saved state through the getter.');
for (const invalid of [null, [], 'bad', { value: undefined }, { value: NaN }, { value: () => 0 }, { value: 1n }, { text: '汉'.repeat(22000) }]) assert.throws(() => sdk.setState(invalid));
const circular = {}; circular.self = circular; assert.throws(() => sdk.setState(circular));
assert.equal(sdk.state.speed, 4, 'Invalid data cannot replace the previous valid state.');
let restored; sdk.onRestore(state => { restored = state; });
port.onmessage({ data: { type: 'restore', value: { speed: 8 } } }); assert.equal(restored.speed, 8);
const count = messages.length; port.onmessage({ data: { type: 'host-command', value: 'delete-everything' } }); assert.equal(messages.length, count);
assert(messages.every(message => ['spellcast:ready', 'ready', 'state'].includes(message.type)));
console.log('PASS: artifact channel identity, JSON boundaries, immutable state snapshots, selections and restoration.');
