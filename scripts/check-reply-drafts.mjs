import assert from 'node:assert/strict';
import { DraftStore, draftKey, draftText, contentKey } from '../src/reply-drafts.ts';

let saved = null;
let fail = false;
const storage = { getItem: () => saved, setItem: (_key, value) => { if (fail) throw new Error('storage unavailable'); saved = value; } };
const make = (source, type = 'text') => ({ source_id: source, reply_id: 'reply', reply_title: 'A thought', block_id: 'body', block_type: type, kind: 'ask', expected_revision: 1, updated_at: 1, text: `Input for ${source}` });
const first = new DraftStore(() => storage);
assert.equal(first.put(make('a')), true);
assert.equal(first.put(make('b')), true);
assert.equal(first.put(make('a', 'graph')), true);
const reloaded = new DraftStore(() => storage);
assert.equal(reloaded.list().length, 3);
assert.equal(reloaded.get(draftKey(make('a'))).text, 'Input for a');
assert.equal(draftText(reloaded.get(draftKey(make('b')))), 'Input for b');
fail = true;
assert.equal(first.put({ ...make('a'), text: 'Latest input survives failed storage' }), false);
assert.equal(first.get(draftKey(make('a'))).text, 'Latest input survives failed storage');
assert.equal(first.hasUnpersisted, true);
fail = false;
assert.equal(first.put({ ...make('b'), text: 'Updated b' }), true);
assert.equal(new DraftStore(() => storage).get(draftKey(make('a'))).text, 'Latest input survives failed storage');
assert.equal(first.put({ ...make('large'), text: 'x'.repeat(1_500_001) }), false);
assert.equal(first.get(draftKey(make('large'))).text.length, 1_500_001);
assert.equal(new DraftStore(() => storage).list().length, 3);
assert.equal(first.remove(draftKey(make('large'))), true);
const secondWindow = new DraftStore(() => storage);
secondWindow.list();
first.put(make('window-one'));
secondWindow.put(make('window-two'));
assert.equal(new DraftStore(() => storage).list().length, 5);
const lateKey = draftKey(make('window-one'));
const oldStamp = first.get(lateKey).updated_at;
secondWindow.put({ ...make('window-one'), text: 'Newer input in another window' });
assert.equal(first.remove(lateKey, oldStamp), false);
assert.equal(new DraftStore(() => storage).get(lateKey).text, 'Newer input in another window');
assert.notEqual(draftKey(make('a')), draftKey({ ...make('a'), channel: 'composer' }));
assert.equal(contentKey({ type: 'text', id: 'x', title: '', text: 'word' }), contentKey({ text: 'word', id: 'x', type: 'text' }));
saved = '{invalid json';
const corrupt = new DraftStore(() => storage);
assert.equal(corrupt.put(make('corrupt')), false);
assert.equal(saved, '{invalid json');
assert.equal(corrupt.get(draftKey(make('corrupt'))).text, 'Input for corrupt');
saved = null;
const legacy = new DraftStore(() => storage), object = { id: 'opaque-object', content: { type: 'reply', id: 'reply' }, content_revision: 1 };
legacy.put(make('a')); legacy.put(make('unrelated-source'));
legacy.bindObjects([object], [{ id: 'reply', source_id: 'a' }]);
const canonical = { ...make('a'), object_id: object.id };
assert.equal(legacy.get(draftKey(canonical)).text, 'Input for a');
assert.equal(legacy.get(draftKey(make('a'))), undefined);
assert.equal(legacy.get(draftKey(make('unrelated-source'))).text, 'Input for unrelated-source');
const again = new DraftStore(() => storage);
again.bindObjects([object], [{ id: 'reply', source_id: 'a' }]);
assert.equal(again.list().length, 2);
again.put({ ...make('a'), text: 'Distinct legacy input' });
again.bindObjects([object], [{ id: 'reply', source_id: 'a' }]);
assert.equal(again.get(draftKey(canonical)).text, 'Input for a');
assert.equal(again.get(draftKey(make('a'))).text, 'Distinct legacy input');
assert.equal(new DraftStore(() => storage).list().length, 3);
const anchored = { ...make('canvas'), channel: 'composer', reply_id: 'canvas:cover', target_source_id: 'story-task', anchors: [
  { object_id: 'cover', content_revision: 3, region: { resource: '/artifacts/cover/main.png', unit: 'normalized', x: .1, y: .2, width: .3, height: .4 } },
  { object_id: 'heading', content_revision: 7 },
] };
assert(again.put(anchored));
assert.deepEqual(new DraftStore(() => storage).get(draftKey(anchored)).anchors, anchored.anchors);
assert.notEqual(draftKey(anchored), draftKey({ ...anchored, target_source_id: 'visual-task' }));
assert.notEqual(draftKey(anchored), draftKey({ ...anchored, anchors: [{ ...anchored.anchors[0], content_revision: 4 }, anchored.anchors[1]] }));
assert.equal(again.put({ ...anchored, anchors: [{ object_id: 'cover', content_revision: 'stale' }] }), false);
saved = null;
const linkedDrafts = new DraftStore(() => storage);
const linked = { ...anchored, anchors: [{ object_id: 'value', content_revision: 3, inputs: { revision: 99, ports: { text: { status: 'available', value: 8, sources: [] } } } }], text: 'Keep this linked draft' };
assert(linkedDrafts.put(linked));
const startup = { ...linked, anchors: [{ ...linked.anchors[0], inputs: { revision: 1, ports: { text: { status: 'unavailable', sources: [] } } } }] };
assert.equal(new DraftStore(() => storage).getComposer(startup).text, linked.text);
assert.deepEqual(linkedDrafts.getComposer(startup).anchors, linked.anchors);
assert.equal(linkedDrafts.getComposer({ ...startup, target_source_id: 'another-task' }), undefined);
assert(linkedDrafts.put({ ...linked, text: 'A separate historical draft', anchors: [{ ...linked.anchors[0], inputs: { ...linked.anchors[0].inputs, revision: 100 } }] }));
assert.equal(linkedDrafts.getComposer(startup), undefined, 'Ambiguous drafts stay available for explicit recovery.');
assert.equal(new DraftStore(() => storage).list().length, 2);
console.log('PASS: draft recovery, failed storage, window merging, legacy preservation and exact multi-anchor routing, including recomputed inputs');
