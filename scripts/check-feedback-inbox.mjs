import assert from 'node:assert/strict';
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { board, feedback, scope } from './fixtures/feedback-inbox.mjs';
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'artifacts/workbench-20260915', `inbox-model-${Date.now()}`); fs.mkdirSync(output, { recursive: true });
const moduleFile = path.join(output, 'feedback-inbox.mjs');
await build({ entryPoints: [path.join(root, 'src/feedback-inbox.ts')], outfile: moduleFile, bundle: true, format: 'esm', platform: 'node' });
const { feedbackInbox, filterInbox } = await import(pathToFileURL(moduleFile).href);
const before = JSON.stringify({ board, feedback });
const entries = feedbackInbox(feedback, board);
assert.equal(entries.length, 8);
assert.deepEqual(filterInbox(entries, scope.workspace, 'all', '', 'followup').map(e => e.row.seq), [5, 4]);
assert.deepEqual(filterInbox(entries, scope.workspace, 'all', '', 'replied').map(e => e.row.seq), [3, 2]);
assert.deepEqual(filterInbox(entries, scope.workspace, 'all', '', 'activity').map(e => e.row.seq), [8, 1]);
assert.equal(entries.find(e => e.row.seq === 6).origin.workspaceKey, 'workspace:g:/examples/calendar');
assert.deepEqual(filterInbox(entries, 'unsorted').map(e => e.row.seq), [7]);
assert.equal(filterInbox(entries, scope.workspace, 'all', '优化 Canvas').length, 6);
assert.equal(filterInbox(entries, scope.workspace, 'all', '半天空档').length, 0);
assert.equal(entries.find(e => e.row.seq === 2).hasResult, false);
assert.equal(entries.find(e => e.row.seq === 3).hasResult, true);
assert.equal(entries.find(e => e.row.seq === 5).row.canRetry, true);
const rebound = structuredClone(feedback); rebound.bindings[0].thread_id = 'replacement'; rebound.bindings[0].cwd = 'G:/Other';
assert.equal(feedbackInbox(rebound, board).find(e => e.row.seq === 4).origin.workspaceKey, scope.workspace);
assert.notEqual(feedbackInbox(rebound, board).find(e => e.row.seq === 5).origin.workspaceKey, 'workspace:g:/other');
const removed = structuredClone(board); removed.canvas.items[0].removed = true;
assert.equal(feedbackInbox(feedback, removed).find(e => e.row.seq === 3).hasResult, false);
assert.equal(JSON.stringify({ board, feedback }), before);
const unassigned = structuredClone(feedback); unassigned.deliveries[6].event.anchors = [{ object_id: 'obj-a', content_revision: 1 }];
assert.equal(feedbackInbox(unassigned, board).find(e => e.row.seq === 7).origin.workspaceKey, 'unsorted');
fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify({ pass: true, assertions: 16, scope: 'Request-level grouping, workspace and recipient provenance, history separation, search, result availability, retry, no fixture mutation' }, null, 2));
console.log(JSON.stringify({ pass: true, output }));
