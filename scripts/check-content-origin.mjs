import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, 'artifacts/workbench-20260914');
fs.mkdirSync(output, { recursive: true });
const modulePath = path.join(output, 'content-origin.mjs');
await build({ entryPoints: [path.join(root, 'src/content-origin.ts')], bundle: true, format: 'esm', platform: 'neutral', outfile: modulePath });
const { workspaceIdentity, resolveContentOrigin, originForObject, originMatches } = await import(pathToFileURL(modulePath).href);
assert.equal(workspaceIdentity('G:\\Projects\\One\\'), workspaceIdentity('g:/projects/one'));
assert.equal(workspaceIdentity('C:\\'), workspaceIdentity('c:/'));
assert.notEqual(workspaceIdentity('/home/One'), workspaceIdentity('/home/one'));
assert.equal(workspaceIdentity('project-one'), 'unsorted');
const a = { project: '同名项目', goal: '整理设计', change: '新增约束', source_id: 'a', captured_at_ms: 1, cwd: 'G:/Projects/A', thread_id: 'thread-a' };
const b = { ...a, source_id: 'b', cwd: 'G:/Projects/B', thread_id: 'thread-b' };
const binding = { source_id: 'a', thread_id: 'thread-a', cwd: a.cwd, label: '设计任务' };
const oa = resolveContentOrigin(a, 'a', [binding]), ob = resolveContentOrigin(b, 'b', []);
assert.notEqual(oa.workspaceKey, ob.workspaceKey);
assert.equal(oa.taskLabel, '设计任务');
const rebound = resolveContentOrigin(a, 'a', [{ ...binding, thread_id: 'different-thread', cwd: b.cwd, label: '其他任务' }]);
assert.equal(rebound.cwd, a.cwd);
assert.equal(rebound.taskKey, 'thread:thread-a');
assert.equal(rebound.taskLabel, a.goal);
assert.equal(resolveContentOrigin({ ...a, cwd: undefined }, 'a', [{ ...binding, thread_id: 'different-thread' }]).workspaceKey, 'unsorted');
const secondTask = resolveContentOrigin({ ...a, thread_id: 'second-thread', source_id: 'second' }, 'second', []);
assert.equal(secondTask.workspaceKey, oa.workspaceKey);
assert.notEqual(secondTask.taskKey, oa.taskKey);
assert.ok(originMatches(oa, oa.workspaceKey, oa.taskKey));
assert.equal(originMatches(ob, oa.workspaceKey), false);
assert.equal(originMatches(secondTask, oa.workspaceKey, oa.taskKey), false);
const original = { id: 'idea', source_id: 'a', captured_context: a };
const board = { nodes: [original], replies: [{ id: 'reply', source_id: 'a', origin_node_id: 'idea' }] };
assert.equal(originForObject({ content: { type: 'reply', id: 'reply' } }, board, []).workspaceKey, oa.workspaceKey);
board.replies[0].source_id = 'b';
assert.equal(originForObject({ content: { type: 'reply', id: 'reply' } }, board, []).workspaceKey, 'unsorted');
assert.equal(resolveContentOrigin(undefined, 'legacy-agent-name', []).workspaceKey, 'unsorted');
assert.equal(original.captured_context, a, 'Reading provenance must not rewrite history.');
console.log('PASS: workspace identity, same-name separation, task boundaries, captured provenance, explicit reply origin, unknown legacy source');
