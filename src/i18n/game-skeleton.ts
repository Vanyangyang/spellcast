export function gs(key: Key, vars?: Record<string, string | number>): string {
  let value: string = currentLocale() === "zh-CN" ? zh[key] : en[key];
  if (vars) for (const [name, replacement] of Object.entries(vars)) value = value.replaceAll(`{${name}}`, String(replacement));
  return value;
}
