export type SigilKey = keyof typeof en;

/** Labels built from server values, such as marker kinds, fall back to the value itself. */
export function st(key: SigilKey, vars: Record<string, string | number> = {}): string {
  let text: string = (currentLocale() === "zh-CN" ? zh : en)[key] ?? key;
  for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, () => String(value));
  return text;
}
